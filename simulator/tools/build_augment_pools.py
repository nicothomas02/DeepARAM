#!/usr/bin/env python3
"""Write data/augment_pools.json: the augments each champion can be offered.

Mayhem's augment pool differs per champion (champion-specific augments, and
ones a champion can never roll). The pool is every augment seen picked on that
champion in the per-champion build stats under ../data/cn/builds/. Champions
without stats fall back to the whole pool in the simulator.

Also writes data/pbe/augment_pools.json for the PBE patch (--game-data data/pbe):
each champion's live pool, less the augments the PBE takes out, plus every
augment new on the PBE (no one has picked those yet, so every champion gets
them and the build search decides). --pbe writes only that file, from the
committed live pools, for the daily PBE refresh (tools/refresh_pbe.sh).
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "..", "data")
BUILDS = os.path.join(HERE, "..", "..", "data", "cn", "builds")


def main():
    with open(os.path.join(DATA, "augments.json"), encoding="utf-8") as f:
        key_of = {a["id"]: k for k, a in json.load(f)["augments"].items()}
    if "--pbe" in sys.argv[1:]:
        with open(os.path.join(DATA, "augment_pools.json"), encoding="utf-8") as f:
            write_pbe(json.load(f)["pools"], set(key_of.values()))
        return
    pools = {}
    for path in sorted(glob.glob(os.path.join(BUILDS, "*.json"))):
        with open(path, encoding="utf-8") as f:
            doc = json.load(f)
        if "augments" not in doc:
            continue
        seen = set()
        for tier in doc["augments"].values():
            seen |= {a["id"] for a in tier}
        pools[str(doc["id"])] = sorted(key_of[i] for i in seen if i in key_of)
    out = {
        "_note": "Augments each champion can be offered in Mayhem, by champion id. "
                 "Generated by tools/build_augment_pools.py.",
        "pools": pools,
    }
    with open(os.path.join(DATA, "augment_pools.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, separators=(",", ":"))
        f.write("\n")
    sizes = [len(p) for p in pools.values()]
    print(f"{len(pools)} champions, {min(sizes)}-{max(sizes)} augments each")
    write_pbe(pools, set(key_of.values()))


def write_pbe(pools, live):
    pbe_path = os.path.join(DATA, "pbe", "augments.json")
    if not os.path.exists(pbe_path):
        return
    with open(pbe_path, encoding="utf-8") as f:
        pbe = set(json.load(f)["augments"])
    new = pbe - live
    pbe_pools = {cid: sorted((set(p) & pbe) | new) for cid, p in pools.items()}
    out = {
        "_note": "Augments each champion can be offered on the PBE patch, by champion id: the live pool less the "
                 "augments the PBE takes out, plus every augment new on the PBE. Generated by "
                 "tools/build_augment_pools.py.",
        "pools": pbe_pools,
    }
    with open(os.path.join(DATA, "pbe", "augment_pools.json"), "w", encoding="utf-8") as f:
        json.dump(out, f, separators=(",", ":"))
        f.write("\n")
    sizes = [len(p) for p in pbe_pools.values()]
    print(f"PBE: {len(new)} new augments, {min(sizes)}-{max(sizes)} augments each")


if __name__ == "__main__":
    main()
