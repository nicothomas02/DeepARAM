"""How the all-champion simulator models each Mayhem augment, by augment id (AugmentPlatformId).

Used by build_augments.py. Each entry gives the augment's stats and effect keys (README.md lists
them) and where each value comes from:
  - a number: written by hand (the note says why);
  - dv("Name"): the augment spell's DataValue;
  - calc("Name"), on a key ending in "_": the spell calculation, split into the effect's amount keys
    (flat, ap, ad, bonus_ad, own_hp, bonus_hp, bonus_armor, bonus_mr; level-based parts become
    "flat_l1"/"flat_l18", which the engine reads at the fight's level);
  - lvl("Name"): a calculation that is only a value by level, as "<key>_l1"/"<key>_l18".
Augments not listed here, or listed in NOT_MODELED, have no effect in the simulator (allies,
gold, summoner spells, map features, random augments...). Notes say what is assumed.

Trigger codes (trig_on, stack_on): 1 attack, 2 ability hit, 3 attack or ability hit, 4 crit,
5 immobilizing an enemy, 6 casting a dash, 7 on its own (a timer), 8 takedown, 9 gaining a
shield, 10 casting the ability the augment is on, 11 channeling, 12 after taking damage.
Damage types (trig_type): 0 physical, 1 magic, 2 true, 3 adaptive.
"""

