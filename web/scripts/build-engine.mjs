// Bundles the shared build engine (src/lib/engine/build-engine.ts) into one plain script for the apps, which have no
// build step: apps/desktop/ui/engine.js (the public app) and public/engine/build-engine.js (served at
// /engine/build-engine.js for Nico's PC app). Both expose window.DeepEngine. tests/unit/build-engine.test.ts fails
// when a copy is out of date: run `node scripts/build-engine.mjs` after changing the engine.
import { buildSync } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
export const ENGINE_SRC = join(web, "src", "lib", "engine", "build-engine.ts");
export const ENGINE_OUT = [join(web, "..", "apps", "desktop", "ui", "engine.js"), join(web, "public", "engine", "build-engine.js")];

export function bundleEngine() {
  const r = buildSync({
    entryPoints: [ENGINE_SRC],
    bundle: true,
    format: "iife",
    globalName: "DeepEngine",
    target: "es2020",
    write: false,
    legalComments: "none",
    charset: "utf8",
  });
  return "// Generated by web/scripts/build-engine.mjs from web/src/lib/engine/build-engine.ts. Do not edit.\n" + r.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const js = bundleEngine();
  for (const f of ENGINE_OUT) {
    mkdirSync(dirname(f), { recursive: true });
    if (!(() => { try { return readFileSync(f, "utf8") === js; } catch { return false; } })()) writeFileSync(f, js);
    console.log(f);
  }
}
